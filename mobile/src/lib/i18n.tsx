// Lightweight typed i18n. A dictionary beats pulling in i18next here: the
// string count is small, and a const-typed catalogue makes a missing or
// misspelled key a compile error rather than a stray key rendered on screen.
//
// The supported set deliberately mirrors what the ANALYSIS backend can return
// (see LANGUAGE_INSTRUCTIONS in server/services/analyzer.ts). Offering a UI
// language whose ingredient explanations come back in English would be a
// broken promise — this is a cross-language product.

export const SUPPORTED_LANGUAGES = ['en', 'zh', 'es'] as const;
export type Language = (typeof SUPPORTED_LANGUAGES)[number];

export const LANGUAGE_NAMES: Record<Language, string> = {
  en: 'English',
  zh: '简体中文',
  es: 'Español',
};

/**
 * The short form, for a control too small to hold a language's full name.
 *
 * Written in each language's OWN script, never as a flag. A flag is a country
 * and a language is not: English is not the United States to the several
 * hundred million people who speak it elsewhere, and putting Spain's flag on
 * Spanish tells nine of every ten Spanish speakers the app was not built with
 * them in mind. It is also the wrong register entirely for a system whose only
 * saturated colour is a verdict.
 *
 * "ZH" would be no better — a person looking for Chinese is looking for 中文.
 */
